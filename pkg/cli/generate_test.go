// smallCollection is one request in one folder: enough that the old importer
// would have produced no steps at all.
const smallCollection = `{
  "info": { "name": "ping" },
  "item": [
    { "name": "Health", "item": [
      { "name": "ping", "request": { "method": "GET", "url": "https://api.test/ping" },
        "response": [{ "name": "ok", "code": 200 }] }
    ]}
  ]
}
`

// writeCollection writes src to a file in a fresh temp directory, the Postman
// counterpart of writeArt and writeYAML.
func writeCollection(t *testing.T, name, src string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

// --flat writes two files, a flow and a scenario file, so it needs -o as the
// collection mode does, and writes nothing without it.
func TestGenerateFlatNeedsOut(t *testing.T) {
	path := writeCollection(t, "ping.postman_collection.json", smallCollection)

	stdout, _, err := executeArgs(t, "generate", "-f", path, "--flat")
	if err == nil {
		t.Fatalf("Execute() = nil, want an error\nstdout:\n%s", stdout)
	}
	if !strings.Contains(err.Error(), "-o") || !strings.Contains(err.Error(), "flow file") {
		t.Errorf("error = %v, want -o and the flow file named", err)
	}
	entries, err := os.ReadDir(filepath.Dir(path))
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 {
		t.Errorf("the directory holds %d files, want only the collection: generate wrote one uninvited", len(entries))
	}
}

// --flat -o writes the flow beside the scenario file and prints nothing. The
// flow holds each request as a step written in place; the scenario file names
// the flow and holds one scenario that sets nothing.
func TestGenerateFlatWritesAFlowAndAScenarioFile(t *testing.T) {
	path := writeCollection(t, "ping.postman_collection.json", smallCollection)
	dir := filepath.Dir(path)
	out := filepath.Join(dir, "ping.art")

	stdout, stderr, err := executeArgs(t, "generate", "-f", path, "--flat", "-o", out)
	if err != nil {
		t.Fatalf("Execute() = %v, want nil\nstderr:\n%s", err, stderr)
	}
	if stdout != "" || stderr != "" {
		t.Errorf("stdout = %q, stderr = %q, want nothing: -o writes to the files", stdout, stderr)
	}

	wantFlow := `# Generated by artemis generate from ping.postman_collection.json.
flow ping {
  step "Health / ping" {
    get "https://api.test/ping"
    expect status == 200
  }
}
`
	if got := readFile(t, filepath.Join(dir, "ping.flow.art")); got != wantFlow {
		t.Errorf("ping.flow.art =\n%s\nwant\n%s", got, wantFlow)
	}
	wantScenario := `# Generated by artemis generate from ping.postman_collection.json.
flow "ping.flow.art"

scenario "ping" {}
`
	if got := readFile(t, out); got != wantScenario {
		t.Errorf("ping.art =\n%s\nwant\n%s", got, wantScenario)
	}
	if _, err := os.Stat(filepath.Join(dir, "ping.collection.art")); err == nil {
		t.Error("--flat wrote a collection file")
	}
}

// The clobber guard. The importer this replaces derived its own filename and
// wrote it into the working directory, so running it twice in a repo replaced
// a file somebody had since edited with no warning and no way to say
// otherwise.
func TestGenerateRefusesToClobberWithoutForce(t *testing.T) {
	path := writeCollection(t, "ping.postman_collection.json", smallCollection)
	out := filepath.Join(filepath.Dir(path), "ping.art")
	const mine = "# my own file\nscenario \"mine\" {\n}\n"
	if err := os.WriteFile(out, []byte(mine), 0o600); err != nil {
		t.Fatal(err)
	}

	_, _, err := executeArgs(t, "generate", "-f", path, "-o", out)
	if err == nil {
		t.Fatal("Execute() = nil, want an error")
	}
	if !strings.Contains(err.Error(), "--force") || !strings.Contains(err.Error(), "ping.art") {
		t.Errorf("error = %v, want the file and --force named", err)
	}

	on, err := os.ReadFile(out) //nolint:gosec // a path this test wrote
	if err != nil {
		t.Fatal(err)
	}
	if string(on) != mine {
		t.Errorf("the file changed:\n%s", on)
	}
}

// --force is the way to say so, and then the file is replaced.
func TestGenerateForceReplacesTheFile(t *testing.T) {
	path := writeCollection(t, "ping.postman_collection.json", smallCollection)
	out := filepath.Join(filepath.Dir(path), "ping.art")
	if err := os.WriteFile(out, []byte("# was here\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if _, stderr, err := executeArgs(t, "generate", "-f", path, "--flat", "-o", out, "--force"); err != nil {
		t.Fatalf("Execute() = %v, want nil\nstderr:\n%s", err, stderr)
	}

	if on := readFile(t, out); !strings.Contains(on, `flow "ping.flow.art"`) {
		t.Errorf("the file was not replaced:\n%s", on)
	}
}

// An error returns rather than being logged and walked past. The version this
// replaces was a `Run` that logged each failure and carried on, so a
// collection that would not parse was followed by a conversion of the zero
// value and the process still exited 0.
func TestGenerateReturnsItsErrors(t *testing.T) {
	cases := []struct {
		name, file, want string
		collection       string
	}{{
		name:       "a file that is not a collection",
		file:       "broken.json",
		collection: `{"info":`,
		want:       "broken.json",
	}, {
		name:       "a formdata body",
		file:       "form.json",
		collection: `{"info":{"name":"c"},"item":[{"name":"up","request":{"method":"POST","url":"https://api.test/u","body":{"mode":"formdata","formdata":[]}}}]}`,
		want:       `"up"`,
	}, {
		name:       "an auth type with no DSL spelling",
		file:       "oauth.json",
		collection: `{"info":{"name":"c"},"auth":{"type":"oauth2","oauth2":[]},"item":[{"name":"p","request":{"method":"GET","url":"https://api.test/p"}}]}`,
		want:       "oauth2",
	}, {
		name:       "a dynamic variable",
		file:       "guid.json",
		collection: `{"info":{"name":"c"},"item":[{"name":"p","request":{"method":"GET","url":"https://api.test/{{$guid}}"}}]}`,
		want:       "dynamic variable",
	}}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			path := writeCollection(t, c.file, c.collection)
			out := filepath.Join(filepath.Dir(path), "out.art")

			stdout, _, err := executeArgs(t, "generate", "-f", path, "--flat", "-o", out)
			if err == nil {
				t.Fatalf("Execute() = nil, want an error\nstdout:\n%s", stdout)
			}
			if !strings.Contains(err.Error(), c.want) {
				t.Errorf("error = %v, want %q in it", err, c.want)
			}
			if stdout != "" {
				t.Errorf("stdout = %q, want nothing: a refused collection writes no source", stdout)
			}
			for _, f := range []string{out, filepath.Join(filepath.Dir(path), "out.flow.art")} {
				if _, err := os.Stat(f); err == nil {
					t.Errorf("%s was written", f)
				}
			}
		})
	}
}

// A failed generation writes no file either, so a half-converted collection
// cannot land on disk.
func TestGenerateWritesNothingWhenItRefuses(t *testing.T) {
	path := writeCollection(t, "guid.json",
		`{"info":{"name":"c"},"item":[{"name":"p","request":{"method":"GET","url":"https://api.test/{{$guid}}"}}]}`)
	out := filepath.Join(filepath.Dir(path), "out.art")

	if _, _, err := executeArgs(t, "generate", "-f", path, "-o", out); err == nil {
		t.Fatal("Execute() = nil, want an error")
	}
	for _, f := range []string{out, collectionPath(out), flowPath(out)} {
		if _, err := os.Stat(f); err == nil {
			t.Errorf("%s was written anyway", f)
		}
	}
}

// The extension guards. Saying so is better than reading a .art file as JSON
// and reporting a syntax error in it, and better still than writing .art
// source into a file called .yaml.
func TestGenerateRefusesTheWrongExtensions(t *testing.T) {
	collection := writeCollection(t, "c.json", smallCollection)

	cases := []struct{ name, file, out, want string }{
		{"a .art input", writeArt(t, "x.art", cleanArt), "", "artemis fmt"},
		{"a .yaml input", writeCollection(t, "x.yaml", "name: x\n"), "", "artemis migrate"},
		{"a .yaml output", collection, "out.yaml", "is not one"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			args := []string{"generate", "-f", c.file}
			if c.out != "" {
				args = append(args, "-o", filepath.Join(t.TempDir(), c.out))
			}
			_, _, err := executeArgs(t, args...)
			if err == nil {
				t.Fatal("Execute() = nil, want an error")
			}
			if !strings.Contains(err.Error(), c.want) {
				t.Errorf("error = %v, want %q in it", err, c.want)
			}
		})
	}
}

// goldenCollection is the fixture the done-when names: nested folders, headers,
// query parameters, a non-JSON body, every auth type that translates, and a
// variable that has to be renamed.
const goldenCollection = "testdata/postman/kitchen_sink.postman_collection.json"

// integrationGenerate is why a test that reads generated files with the parser
// is skipped until the parser reads collection items with var inputs, step
// calls, flow files and scenario files, and expansion runs a scenario file.
const integrationGenerate = "integration: needs Tasks 2-6,9"

// goldenGenerated is every file a mode writes, by the golden it is pinned to:
// testdata/postman/<mode>/<file>.
var goldenGenerated = map[string][]string{
	"collection": {"kitchen_sink.collection.art", "kitchen_sink.flow.art", "kitchen_sink.art"},
	"flat":       {"kitchen_sink.flow.art", "kitchen_sink.art"},
}

// goldenPath is the golden for one generated file.
func goldenPath(mode, file string) string {
	return filepath.Join("testdata", "postman", mode, file)
}

// TestGoldenPostmanGenerate pins the whole of a generation, in both modes,
// rather than the lines a test happens to assert on. Named for `make golden`,
// which runs `-run TestGolden -update` over this package.
func TestGoldenPostmanGenerate(t *testing.T) {
	for mode, files := range goldenGenerated {
		t.Run(mode, func(t *testing.T) {
			out := filepath.Join(t.TempDir(), "kitchen_sink.art")
			args := []string{"generate", "-f", goldenCollection, "-o", out}
			if mode == "flat" {
				args = append(args, "--flat")
			}
			if _, stderr, err := executeArgs(t, args...); err != nil {
				t.Fatalf("Execute() = %v, want nil\nstderr:\n%s", err, stderr)
			}
			for _, f := range files {
				got := readFile(t, filepath.Join(filepath.Dir(out), f))
				path := goldenPath(mode, f)
				if *update {
					if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
						t.Fatal(err)
					}
					if err := os.WriteFile(path, []byte(got), 0o600); err != nil {
						t.Fatal(err)
					}
					continue
				}
				want, err := os.ReadFile(path) //nolint:gosec // a path this test built
				if err != nil {
					t.Fatalf("%v\nrun `make golden` and read the diff", err)
				}
				if got != string(want) {
					t.Errorf("generating %s gave %s\n%s\nthe golden holds\n%s", goldenCollection, f, got, want)
				}
			}
		})
	}
}

// The done-when's first half: the generated files parse and check clean, with
// no diagnostics at all. A generated file artemis would refuse is an importer
// nobody can adopt. The scenario file is compiled, which reads the flow and the
// collection beside it.
func TestGeneratedGoldenChecksClean(t *testing.T) {
	t.Skip(integrationGenerate)
	for mode := range goldenGenerated {
		path := goldenPath(mode, "kitchen_sink.art")
		bag := frontEnd(path, readFile(t, path)).Bag
		for _, d := range bag.All() {
			t.Errorf("%s: %s:%d: %s: %s", mode, d.Span.File, d.Span.Line, d.Code, d.Message)
		}
	}
}

// And its second: the output is already canonical, so `artemis fmt` would not
// change a generated file. generate writes the canonical form as text rather
// than printing a tree, so this is what holds the two to each other.
func TestGeneratedGoldenIsCanonical(t *testing.T) {
	t.Skip(integrationGenerate)
	for mode, files := range goldenGenerated {
		for _, f := range files {
			path := goldenPath(mode, f)
			src := readFile(t, path)
			tree, bag := parser.Parse(path, src)
			if bag.HasErrors() {
				t.Errorf("%s does not parse: %v", path, bag.All()[0])
				continue
			}
			if got := print.Canonical(tree); got != src {
				t.Errorf("%s is not canonical; artemis fmt would write\n%s", path, got)
			}
		}
	}
}

// The folder walk, read off the goldens: every request in the fixture is a
// step of the flow, in collection order, and the empty folder is not -- in
// both modes.
func TestGoldenCoversEveryRequest(t *testing.T) {
	want := []string{
		`step "Health / ping"`,
		`step "Orders / Admin / list orders"`,
		`step "Orders / create order"`,
		`step "Orders / amend order"`,
		`step "Orders / search orders"`,
		`step "Legacy / raw header form"`,
	}
	for mode := range goldenGenerated {
		src := readFile(t, goldenPath(mode, "kitchen_sink.flow.art"))
		at := -1
		for _, w := range want {
			i := strings.Index(src, w)
			if i < 0 {
				t.Errorf("%s: %s is missing from the flow", mode, w)
				continue
			}
			if i < at {
				t.Errorf("%s: %s is out of collection order", mode, w)
			}
			at = i
		}
		for _, gone := range []string{"Empty folder", "X-Trace", "cursor", "void", "retry"} {
			if strings.Contains(src, gone) {
				t.Errorf("%s: %q should not be in the flow", mode, gone)
			}
		}
	}
}
